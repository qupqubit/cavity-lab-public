"""Generate the public sample from elementary geometry, without external CAD.

Run from an installed source tree: python scripts/generate_samples.py
Optional --validate runs the Maxwell solve and writes a compact generic report.
"""
import argparse
import json
import math
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def generate(destination):
    from netgen.occ import Cylinder, Pnt, Vec
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    path = destination/'cylinder-vacuum.step'
    Cylinder(Pnt(0, 0, 0), Vec(0, 0, 1), 15, 20).WriteStep(str(path))
    metadata = {
        'sample': 'Circular vacuum cavity', 'units': 'mm',
        'geometry_mode': 'vacuum_solid', 'radius_mm': 15, 'height_mm': 20,
        'source': 'Analytic cylinder generated by scripts/generate_samples.py; no external CAD',
        'analytic_mode': 'TM010',
        'analytic_frequency_ghz': 299792458.0*2.404825557695773/(2*math.pi*.015)/1e9,
        'loss_note': 'All boundaries are PEC for the ideal frequency reference. The UI surface resistance of 10 nOhm is illustrative, not a material measurement.',
        'suggested_config': {'geometry_mode': 'vacuum_solid', 'maxh_mm': 4, 'order': 2,
                             'n_modes': 1, 'target_ghz': 8, 'loss_model': 'surface_rs',
                             'rs_nohm': 10, 'oxide_thickness_nm': 0, 'oxide_epsr': 1, 'oxide_tand': 0}}
    (destination/'cylinder.json').write_text(json.dumps(metadata, indent=2)+'\n', encoding='utf-8')
    return path, metadata


def validate(path, metadata):
    from cavity_fem.config import SolveConfig
    from cavity_fem.solver import C0, MU0, solve
    config = SolveConfig(geometry_mode='vacuum_solid', maxh_mm=4, order=3, n_modes=1,
                         target_ghz=8, loss_model='none', threads=1, field_resolution=11,
                         mode_search='lowest', spectrum_start_ghz=.1, spectrum_stop_ghz=15)
    with tempfile.TemporaryDirectory(prefix='cavity-lab-validation-') as directory:
        result = solve(path, config, output_dir=directory)
        mode = result['modes'][0]
        fields = json.loads((Path(directory)/mode['field_file']).read_text(encoding='utf-8'))
        magnitudes = [v for p in fields['planes'] for v in p['magnitude'] if v is not None]
        field_export = {'planes': len(fields['planes']), 'maximum_relative_e': max(magnitudes),
                        'vtu_exists': (Path(directory)/'mode_01.vtu').is_file()}
    frequency = metadata['analytic_frequency_ghz']
    geometry_factor = 2*math.pi*frequency*1e9*MU0*.015*.020/(2*(.015+.020))
    surface_electric = 2/.020
    report = {
        'sample': 'cylinder-vacuum.step', 'solver': result['solver'], 'solver_version': result['solver_version'],
        'boundary_condition': 'PEC on every exterior face', 'config': config.model_dump(),
        'reference': {'mode': 'TM010', 'frequency_ghz': frequency,
                      'geometry_factor_ohm': geometry_factor, 'surface_electric_per_m': surface_electric},
        'computed': {key: mode[key] for key in ('frequency_ghz', 'geometry_factor_ohm', 'surface_electric_per_m',
                                               'residual', 'energy_balance_relative', 'qi', 'ports')},
        'relative_errors': {'frequency': abs(mode['frequency_ghz']/frequency-1),
                            'geometry_factor': abs(mode['geometry_factor_ohm']/geometry_factor-1),
                            'surface_electric': abs(mode['surface_electric_per_m']/surface_electric-1)},
        'field_export': field_export, 'mesh': result['mesh'], 'mode_search': result.get('mode_search'),
        'timings_seconds': result['timings'],
        'limits': ['This single mesh is an analytic smoke test, not a convergence study.',
                   'The lowest mode is found within the specified search band; completeness is not proved.',
                   'Qi is null for this lossless reference; finite Qi requires material loss inputs.']}
    assert report['relative_errors']['frequency'] < 2e-4
    assert report['relative_errors']['geometry_factor'] < .003
    assert report['relative_errors']['surface_electric'] < .003
    assert field_export['planes'] == 3 and field_export['maximum_relative_e'] == 1
    assert field_export['vtu_exists']
    (path.parent/'validation.json').write_text(json.dumps(report, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    return report


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--validate', action='store_true')
    args = parser.parse_args()
    path, metadata = generate(ROOT/'examples')
    if args.validate:
        report = validate(path, metadata)
        print(json.dumps(report['relative_errors'], indent=2))
    else:
        print('Generated examples/cylinder-vacuum.step and cylinder.json')


if __name__ == '__main__':
    main()
